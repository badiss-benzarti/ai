package com.travelmate.itinerary.service;

import com.travelmate.itinerary.dto.BudgetSummaryDto;
import com.travelmate.itinerary.dto.DayDto;
import com.travelmate.itinerary.dto.ItemDto;
import com.travelmate.itinerary.dto.ItineraryDto;
import lombok.RequiredArgsConstructor;
import org.openpdf.text.*;
import org.openpdf.text.pdf.PdfPCell;
import org.openpdf.text.pdf.PdfPTable;
import org.openpdf.text.pdf.PdfWriter;
import org.springframework.stereotype.Service;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.time.LocalTime;
import java.time.format.DateTimeFormatter;
import java.util.Locale;

/** Exports an itinerary as a PDF (OpenPDF). */
@Service
@RequiredArgsConstructor
public class PdfService {

    private static final Color PRIMARY = new Color(0x1E, 0x5A, 0x8C);
    private static final Color LIGHT = new Color(0xEE, 0xF3, 0xF8);
    private static final DateTimeFormatter DATE = DateTimeFormatter.ofPattern("EEEE dd MMM yyyy", Locale.ENGLISH);
    private static final DateTimeFormatter TIME = DateTimeFormatter.ofPattern("HH:mm");

    private static final Font TITLE = new Font(Font.HELVETICA, 22, Font.BOLD, PRIMARY);
    private static final Font SUBTITLE = new Font(Font.HELVETICA, 11, Font.NORMAL, Color.DARK_GRAY);
    private static final Font DAY = new Font(Font.HELVETICA, 14, Font.BOLD, PRIMARY);
    private static final Font HEADER = new Font(Font.HELVETICA, 10, Font.BOLD, Color.WHITE);
    private static final Font CELL = new Font(Font.HELVETICA, 10, Font.NORMAL, Color.BLACK);
    private static final Font NOTE = new Font(Font.HELVETICA, 8, Font.ITALIC, Color.GRAY);
    private static final Font BOLD = new Font(Font.HELVETICA, 11, Font.BOLD, Color.BLACK);
    private static final Font ALERT = new Font(Font.HELVETICA, 11, Font.BOLD, new Color(0xC0, 0x39, 0x2B));
    private static final Font OK = new Font(Font.HELVETICA, 11, Font.BOLD, new Color(0x1E, 0x84, 0x49));

    private final ItineraryService itineraryService;
    private final BudgetService budgetService;

    public byte[] export(Long itineraryId) {
        ItineraryDto it = itineraryService.getById(itineraryId);
        BudgetSummaryDto budget = budgetService.summary(itineraryId);

        ByteArrayOutputStream out = new ByteArrayOutputStream();
        Document doc = new Document(PageSize.A4, 40, 40, 40, 40);
        PdfWriter.getInstance(doc, out);
        doc.open();

        doc.add(new Paragraph("TravelMate - " + it.destination(), TITLE));
        doc.add(new Paragraph(it.startDate() + " to " + it.endDate() + "  |  " + it.days().size() + " days"
                + (it.generatedByAi() ? "  |  generated by AI" : ""), SUBTITLE));
        doc.add(Chunk.NEWLINE);

        for (DayDto day : it.days()) {
            Paragraph dayTitle = new Paragraph("Day " + day.dayNumber() + " - " + day.title(), DAY);
            dayTitle.setSpacingBefore(8);
            doc.add(dayTitle);
            doc.add(new Paragraph(capitalize(day.date().format(DATE)), SUBTITLE));
            doc.add(dayTable(day));
        }

        doc.add(Chunk.NEWLINE);
        doc.add(new Paragraph("Budget summary", DAY));
        doc.add(new Paragraph(String.format("Budget: %.2f EUR", budget.budget()), BOLD));
        doc.add(new Paragraph(String.format("Estimated cost: %.2f EUR", budget.estimatedTotal()), BOLD));
        if (budget.spentTotal() > 0) {
            doc.add(new Paragraph(String.format("Already spent: %.2f EUR", budget.spentTotal()), BOLD));
        }
        doc.add(budget.overBudget()
                ? new Paragraph(String.format("Over budget by %.2f EUR", -budget.remainingEstimated()), ALERT)
                : new Paragraph(String.format("Within budget, %.2f EUR left", budget.remainingEstimated()), OK));

        doc.close();
        return out.toByteArray();
    }

    private PdfPTable dayTable(DayDto day) {
        PdfPTable table = new PdfPTable(new float[]{1.3f, 1.4f, 5f, 1.6f});
        table.setWidthPercentage(100);
        table.setSpacingBefore(4);
        for (String h : new String[]{"Time", "Type", "What", "Cost"}) {
            PdfPCell cell = new PdfPCell(new Phrase(h, HEADER));
            cell.setBackgroundColor(PRIMARY);
            cell.setPadding(5);
            table.addCell(cell);
        }
        boolean shaded = false;
        for (ItemDto item : day.items()) {
            Color bg = shaded ? LIGHT : Color.WHITE;
            shaded = !shaded;
            table.addCell(cell(time(item.startTime()) + (item.endTime() != null ? " - " + time(item.endTime()) : ""), bg));
            table.addCell(cell(capitalize(item.type().name().toLowerCase()), bg));

            Paragraph what = new Paragraph(item.name(), CELL);
            if (item.notes() != null && !item.notes().isBlank()) {
                what.add(new Chunk("\n" + item.notes(), NOTE));
            }
            PdfPCell whatCell = new PdfPCell(what);
            whatCell.setBackgroundColor(bg);
            whatCell.setPadding(5);
            table.addCell(whatCell);

            PdfPCell cost = cell(String.format("%.2f EUR", item.estimatedCost()), bg);
            cost.setHorizontalAlignment(Element.ALIGN_RIGHT);
            table.addCell(cost);
        }
        PdfPCell totalLabel = new PdfPCell(new Phrase("Day total", BOLD));
        totalLabel.setColspan(3);
        totalLabel.setPadding(5);
        table.addCell(totalLabel);
        PdfPCell total = new PdfPCell(new Phrase(String.format("%.2f EUR", day.dayCost()), BOLD));
        total.setHorizontalAlignment(Element.ALIGN_RIGHT);
        total.setPadding(5);
        table.addCell(total);
        return table;
    }

    private PdfPCell cell(String text, Color bg) {
        PdfPCell cell = new PdfPCell(new Phrase(text, CELL));
        cell.setBackgroundColor(bg);
        cell.setPadding(5);
        return cell;
    }

    private String time(LocalTime t) {
        return t == null ? "" : t.format(TIME);
    }

    private static String capitalize(String s) {
        return s == null || s.isEmpty() ? "" : Character.toUpperCase(s.charAt(0)) + s.substring(1);
    }
}
